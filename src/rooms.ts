/**
 * Rooms are text grids (legend in level.ts). A run walks through them in order;
 * each room's square exit opens once every enemy in it is gone.
 *
 * The tutorial rooms teach one idea each, with no words: the layout is the lesson.
 *   move      walk, jump, a step, a shallow pit, a wall worth a full jump
 *   attack    one enemy that never strikes back; the triangle makes it bleed circles
 *   telegraph one grunt with room to back off: its growing triangle means "now move"
 *   guard     a low corridor with no room to jump over: the square is the way through
 *   health    fragile hoppers leave circles; walking through them gives health back
 *   weapon    a hammer lies before a warden whose square stops the sword
 *   exit      the square is in sight from the start; a brute stands before it
 */

