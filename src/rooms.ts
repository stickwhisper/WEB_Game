const room = (id: string): RoomDef => ({ id, grid: GRIDS[id] });

export const TUTORIAL: RoomDef[] = ['move', 'attack', 'telegraph', 'guard', 'health', 'weapon', 'exit'].map(room);
export const POOL: RoomDef[] = ['corridor', 'steps', 'pit', 'wardens', 'hall', 'towers', 'low', 'mixed'].map(room);
export const BOSS: RoomDef = room('boss');

/** The same room, left to right reversed (spawn and exit swap sides with everything else). */
export function mirrored(r: RoomDef): RoomDef {
  return { id: `${r.id}~`, grid: r.grid.map((row) => [...row].reverse().join('')) };
}
